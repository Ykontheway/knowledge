// Python models -> independent mutation JSON schema -> TypeScript. No B1 imports.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, "../src/mutations/schema.json");
const outputPath = resolve(here, "../src/mutations/types.gen.ts");
const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const names = Object.keys(schema.$defs);
const generated = await compile({
  ...schema,
  properties: Object.fromEntries(names.map((name) => [name, { $ref: `#/$defs/${name}` }])),
  required: names,
}, "MutationApiSchemaBundle", {
  bannerComment: "/* Generated by `node web/scripts/gen-mutation-types.mjs` from actual Pydantic mutation schemas. Do not edit. */",
  additionalProperties: false,
  strictIndexSignatures: true,
  style: { singleQuote: false, semi: true, printWidth: 100 },
});
if (process.argv.includes("--check")) {
  if (await readFile(outputPath, "utf8").catch(() => "") !== generated) {
    console.error("Mutation types are out of date; run node web/scripts/gen-mutation-types.mjs");
    process.exit(1);
  }
  console.log("Mutation types are up to date.");
} else {
  await writeFile(outputPath, generated);
  console.log(`Wrote ${outputPath}`);
}
